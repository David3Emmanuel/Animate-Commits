export function fallbackColors(kind: ThemeKind): Record<string, string> {
  return kind === 'light' || kind === 'hc-light' ? { ...LIGHT } : { ...DARK };
}

export function defaultUiFont(platform: NodeJS.Platform): string {
  if (platform === 'win32') return '"Segoe UI", "Segoe UI Variable Text", system-ui, sans-serif';
  if (platform === 'darwin') return '-apple-system, BlinkMacSystemFont, "SF Pro Text", system-ui, sans-serif';
  return 'system-ui, Ubuntu, "Droid Sans", Cantarell, sans-serif';
}

export function defaultEditorFont(platform: NodeJS.Platform): string {
  if (platform === 'win32') return 'Consolas, "Courier New", monospace';
  if (platform === 'darwin') return 'Menlo, Monaco, "Courier New", monospace';
  return '"Droid Sans Mono", "DejaVu Sans Mono", monospace';
}
